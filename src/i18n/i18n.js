function normalizeLocale(locale){
  const short=String(locale||'').toLowerCase().split('-')[0];
  return SUPPORTED_LOCALES.includes(short)?short:DEFAULT_LOCALE;
}
function interpolate(template,params){
  return String(template).replace(/\{(\w+)\}/g,(match,key)=>
    Object.prototype.hasOwnProperty.call(params,key)?String(params[key]):match);
}
function t(key,params={}){
  const template=dictionaries[currentLocale][key]??dictionaries.en[key]??key;
  return interpolate(template,params);
}
function gameDataText(group,index,field,polishFallback=''){
  if(currentLocale==='pl')return polishFallback;
  const row=englishGameData[group]?.[index];
  return row?.[field==='name'||field==='label'||field==='bonusDesc'?0:1]??polishFallback;
}
function setLocale(locale){
  currentLocale=normalizeLocale(locale);
  if(globalThis.document?.documentElement)document.documentElement.lang=currentLocale;
  localizeStatic();
  return currentLocale;
}
function getLocale(){return currentLocale;}
function localeTag(locale=currentLocale){return normalizeLocale(locale)==='pl'?'pl-PL':'en-US';}
function formatNumber(value,options){return new Intl.NumberFormat(localeTag(),options).format(value);}
function formatCurrency(value){return new Intl.NumberFormat(localeTag(),{style:'currency',currency:'EUR',maximumFractionDigits:0}).format(value);}
function formatDateTime(value){return new Intl.DateTimeFormat(localeTag(),{dateStyle:'medium',timeStyle:'short'}).format(new Date(value));}
function localizeStatic(root=globalThis.document){
  if(!root?.querySelectorAll)return;
  root.querySelectorAll('[data-i18n]').forEach(el=>{el.textContent=t(el.dataset.i18n);});
  root.querySelectorAll('[data-i18n-label]').forEach(el=>{el.dataset.label=t(el.dataset.i18nLabel);});
  root.querySelectorAll('[data-i18n-title]').forEach(el=>{el.title=t(el.dataset.i18nTitle);});
}

